// elements.h — the periodic table, for the atom face.
//
// Symbol and electrons per shell for all 118 elements, checked at generation
// time by asserting each configuration sums to its atomic number. Seven shells
// is the most any of them uses. About 1.2KB of flash, which the Teensy has.
//
// Shell occupancy is the Bohr/Madelung picture, which is what a shell diagram
// draws; it is not the orbital notation, and for a handful of transition metals
// (Cr, Cu, Nb, Mo, Ru, Rh, Pd, Ag, Pt, Au) the two disagree. The values here are
// the observed configurations, which are what those elements actually do.
// SPDX-License-Identifier: GPL-2.0-or-later
